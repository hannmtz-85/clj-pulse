(defn- message-alert
  "What Keycloak says about the page in a message of its own (an error, a warning, a success or a note), as an alert of
  the tone that fits."
  []
  (let [alert (fn [tone] (c/alert {:tone tone :role "alert" :title (ftl "${kcSanitize(message.summary)?no_esc}")}))]
    (when-ftl "displayMessage && message?has_content && (message.type != 'warning' || !isAppInitiatedAction??)"
              (ftl "<#if message.type = 'error'>") (alert :critical)
              (ftl "<#elseif message.type = 'warning'>") (alert :high)
              (ftl "<#elseif message.type = 'success'>") (alert :normal)
              (ftl "<#else>") (alert :info)
              (ftl "</#if>"))))

(defn- attempted-username
  "The name that was typed, with the way to start again, for a page of the second step of a sign-in."
  []
  (when-ftl "auth?has_content && auth.showUsername() && !auth.showResetCredentials()"
            (ftl "<#nested \"show-username\">")
            [:p {:id "kc-username" :class "mt-3 flex flex-wrap items-center gap-x-3 gap-y-1 text-sm"}
             [:span {:id "kc-attempted-username" :class "font-medium"} (ftl "${auth.attemptedUsername}")]
             [:a {:id "reset-login" :class "link link-primary" :href "${url.loginRestartFlowUrl}"} (msg "restartLoginTooltip")]]))

(defn- try-another-way []
  (when-ftl "auth?has_content && auth.showTryAnotherWayLink()"
            [:form {:id "kc-select-try-another-way-form" :class "mt-4" :action "${url.loginAction}" :method "post"}
             [:input {:type "hidden" :name "tryAnotherWay" :value "on"}]
             [:a {:id "try-another-way" :class "link link-primary text-sm font-medium" :href "#"
                  :onclick "document.forms['kc-select-try-another-way-form'].submit(); return false;"}
              (msg "doTryAnotherWay")]]))

(defn- head []
  [:head
   [:meta {:charset "utf-8"}]
   [:meta {:name "viewport" :content "width=device-width, initial-scale=1"}]
   [:meta {:name "color-scheme" :content "light dark"}]
   [:meta {:name "robots" :content "noindex, nofollow"}]
   [:title (msg "loginTitle" "(realm.displayName!'')")]
   [:link {:rel "icon" :type "image/svg+xml" :href "${url.resourcesPath}/img/favicon.svg"}]
   [:link {:rel "stylesheet" :href "${url.resourcesPath}/pulse.css"}]
   (ftl "<script type=\"importmap\">{\"imports\":{\"rfc4648\":\"${url.resourcesCommonPath}/vendor/rfc4648/rfc4648.js\"}}</script>")
   (when-ftl "scripts??" (ftl "<#list scripts as script><script src=\"${script}\" type=\"text/javascript\"></script></#list>"))
   ;; the script of Keycloak that notices that someone signed in in another tab
   (ftl "<script type=\"module\">import { checkCookiesAndSetTimer } from \"${url.resourcesPath}/js/authChecker.js\"; "
        "checkCookiesAndSetTimer(\"${url.ssoLoginInOtherTabsUrl?no_esc}\");</script>")])

(defn- card []
  [:div {:class layout/login-card-class}
   (layout/login-title :h1 {:id "kc-page-title"} (ftl "<#nested \"header\">"))
   ;; a page may have a line under its title, and the title is alone when it has none
   (ftl "<#local subtitle><#nested \"subtitle\"></#local>")
   (when-ftl "subtitle?has_content" (layout/login-subtitle (ftl "${subtitle}")))
   (when-ftl "displayRequiredFields"
             [:p {:class "mt-1 text-sm text-muted"} [:span {:aria-hidden "true"} "*"] " " (msg "requiredFields")])
   (attempted-username)
   [:div {:id "kc-content" :class layout/login-content-class}
    (message-alert)
    (ftl "<#nested \"form\">")
    (try-another-way)
    (ftl "<#nested \"socialProviders\">")
    (when-ftl "displayInfo" (layout/login-info {:id "kc-info"} (ftl "<#nested \"info\">")))]])

(defn- template-ftl
  "The layout that every page uses: Keycloak calls it as a macro, with the sections of the page nested in it."
  []
  (str "<#macro registrationLayout bodyClass=\"\" displayInfo=false displayMessage=true displayRequiredFields=false>\n"
       "<!DOCTYPE html>\n"
       "<html<#if realm.internationalizationEnabled> lang=\"${locale.currentLanguageTag}\" dir=\"${(locale.rtl)?then('rtl','ltr')}\"<#else> lang=\"en\"</#if>>"
       (render (head))
       (render [:body {:class "min-h-screen bg-base-200 text-base-content antialiased"}
                (layout/login-frame {:notice (msg "demoNotice")} (card))])
       "</html>\n"
       "</#macro>\n"))

