(ns pulse.design.keycloak
  "The login theme of Keycloak (ADR-0026): its templates, its messages, its properties and its icon, made from the
  components of `libs/ui` that the mock-ups are made from, so that a page of the real login is the page of the review:
  the same card, the same alert, the same buttons and fields, and the same English as the mock-ups, which read
  `messages`. The templates are FreeMarker, and Keycloak fills them in at run time; what changes with a realm or a
  request (a name, a link, an error, a setting) is raw FreeMarker among the hiccup.

  The theme extends `base`, which has the templates of every page that Keycloak can show and no stylesheet, and rewrites
  the pages that the realm uses: the sign-in, an error, a message, the question before signing out and the page that
  has expired. The others (updating a password, a one-time code) keep the markup of `base` inside the frame of this
  theme, with the classes that `theme.properties` gives it. The stylesheet is the one of the interfaces, compiled
  from the same tokens (`bb design:keycloak`). `write!` writes what this namespace makes, and `check` finds what a
  committed file lacks or has too much of."
  (:require [clojure.java.io :as io]
            [clojure.string :as str]
            [design]
            [hiccup2.core :as h]
            [pulse.ui.component :as c]
            [pulse.ui.icon :as i]
            [pulse.ui.layout :as layout]))

