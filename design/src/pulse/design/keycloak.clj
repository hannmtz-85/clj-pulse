       "# What this theme words differently from Keycloak, or adds; the rest is Keycloak's, from the theme `base`.\n"
       (str/join (for [[k text] messages] (str k "=" text "\n")))))

;; ---------------------------------------------------------------------------
;; FreeMarker among the hiccup

(defn- ftl
  "FreeMarker text that hiccup must not escape: a directive, or an interpolation."
  [& parts]
  (h/raw (apply str parts)))

(defn- msg
  "The interpolation of a message of Keycloak, with the FreeMarker expressions that are its arguments."
  [k & args]
  (ftl "${msg(\"" k "\"" (apply str (for [a args] (str ", " a))) ")}"))

(defn- when-ftl
  "`content` only when the FreeMarker `condition` is true."
  [condition & content]
  (list (ftl "<#if " condition ">") content (ftl "</#if>")))

(defn- either-ftl
  "`then` when the FreeMarker `condition` is true, and `otherwise` when it is not."
  [condition then otherwise]
  (list (ftl "<#if " condition ">") then (ftl "<#else>") otherwise (ftl "</#if>")))

(defn- render
  "The text of hiccup, as the theme writes it: HTML, with the raw FreeMarker as it is."
  [hiccup]
  (str (h/html {:mode :html} hiccup)))

(def ^:private credentials-error
  "When Keycloak says that the name or the password are wrong."
  "messagesPerField.existsError('username','password')")

