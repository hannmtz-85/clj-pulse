(defn message
  "The English text of the message `k` of the theme or of Keycloak, for a page of the review (which has no Keycloak to
  ask), with `{0}` and the like replaced by the arguments."
  [k & args]
  (let [text (or (get messages (name k)) (get base-messages (name k)))]
    (when-not text
      (throw (ex-info (str "Neither the theme nor Keycloak has a message called " (pr-str k))
                      {:message k :known (concat (keys messages) (keys base-messages))})))
    (reduce-kv (fn [s n arg] (str/replace s (str "{" n "}") (str arg))) text (vec args))))

