(defn font-files
  "The font files the tokens name, which the stylesheet of the theme asks for under `resources/fonts`."
  []
  (map :file (get-in (design/read-tokens) [:font :faces])))

(def font-license
  "The license of the font, which goes wherever the font goes: the SIL Open Font License asks for it in every copy."
  "OFL.txt")

(defn- copied-files
  "The files of `design/fonts` that the theme keeps beside its stylesheet: the font and its license."
  []
  (concat (font-files) [font-license]))

(defn- theme-file ^java.io.File [path] (io/file theme-dir path))

(defn check
  "What a committed file lacks: a sorted vector of paths that are not what `files` makes, or that are missing, and the files
  of the font (the font and its license) in the theme that are not those of `design/fonts`."
  []
  (vec (sort (concat (for [[path text] (files)
                           :let [file (theme-file path)]
                           :when (or (not (.exists file)) (not= text (slurp file :encoding "UTF-8")))]
                       path)
                     (for [font (copied-files)
                           :let [committed (theme-file (str "resources/fonts/" font))
                                 source (io/file fonts-dir font)]
                           :when (or (not (.exists committed))
                                     (not (java.util.Arrays/equals (java.nio.file.Files/readAllBytes (.toPath committed))
                                                                   (java.nio.file.Files/readAllBytes (.toPath source)))))]
                       (str "resources/fonts/" font))))))

(defn write!
  "Writes the templates, the messages, the properties and the icon into the directory of the theme, and copies the font
  and its license there."
  []
  (doseq [[path text] (files)
          :let [file (theme-file path)]]
    (io/make-parents file)
    (spit file text :encoding "UTF-8")
    (println "Wrote" (str file)))
  (doseq [font (copied-files)
          :let [target (theme-file (str "resources/fonts/" font))]]
    (io/make-parents target)
    (io/copy (io/file fonts-dir font) target)
    (println "Copied" (str target))))
