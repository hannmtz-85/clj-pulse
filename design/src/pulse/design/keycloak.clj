(defn theme-properties-file
  "The text of `theme.properties`. The classes are written after ` = ` and not after `=`: Tailwind reads the classes of
  this file as it reads the templates, and would take the first of each, joined to the name of the property, for
  something that is not a class."
  []
  (str "# Generated by `bb design:keycloak` from pulse.design.keycloak. Do not edit it (ADR-0026).\n"
       "parent = base\n"
       "styles = pulse.css\n"
       "# The markup of the pages of base that this theme does not rewrite asks for these classes.\n"
       (str/join (for [[k classes] class-properties] (str k " = " classes "\n")))))

(defn favicon-svg
  "The mark of Pulse as an SVG for the tab of the browser, in the colours of the palette."
  []
  (let [tokens (design/read-tokens)
        {:keys [primary primary-content]} (get-in tokens [:palettes (get-in tokens [:palette :selected]) :light])
        shapes (drop 2 (i/icon :heart-pulse))]
    (str (h/html {:mode :xml}
                 [:svg {:xmlns "http://www.w3.org/2000/svg" :viewBox "0 0 32 32" :width 32 :height 32}
                  [:rect {:width 32 :height 32 :rx 8 :fill primary}]
                  (into [:g {:transform "translate(4 4)" :fill "none" :stroke primary-content :stroke-width 2
                             :stroke-linecap "round" :stroke-linejoin "round"}]
                        shapes)]) "\n")))

