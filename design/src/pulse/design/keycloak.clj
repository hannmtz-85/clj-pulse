(defn- page
  "A page of the theme: it imports the layout, and each of its sections, written in hiccup, is chosen by FreeMarker
  from the name Keycloak gives it. `options` are the arguments of the layout. The sections are on the one line of the
  call, because a line break in them would be written in every section, and a section that has nothing to say would
  not be empty."
  [options sections]
  (str "<#import \"template.ftl\" as layout>\n"
       "<@layout.registrationLayout" (apply str (for [[k v] options] (str " " k "=(" v ")"))) "; section>"
       (apply str (for [[n [section-name section-hiccup]] (map-indexed vector sections)]
                    (str (if (zero? n) "<#if " "<#elseif ") "section = \"" section-name "\">"
                         (render section-hiccup))))
       "</#if></@layout.registrationLayout>\n"))

(defn- username-field [error?]
  (c/text-field (cond-> {:id "username" :name "username" :type "text" :dir "ltr" :autocomplete "username"
                         :value "${login.username!}"
                         :label (ftl "<#if !realm.loginWithEmailAllowed>${msg(\"username\")}"
                                     "<#elseif !realm.registrationEmailAsUsername>${msg(\"usernameOrEmail\")}"
                                     "<#else>${msg(\"email\")}</#if>")}
                  error? (assoc :aria-invalid "true" :class "input-error")
                  (not error?) (assoc :autofocus true))))

(defn- password-field
  "The password. It has the cursor when it is the field to type again (after an error) or the first one (when the name is
  not asked); `mode` is `:error`, `:first` or `:plain`."
  [mode]
  (c/text-field (cond-> {:id "password" :name "password" :type "password" :autocomplete "current-password"
                         :label (msg "password")}
                  (= :error mode) (assoc :aria-invalid "true" :class "input-error")
                  (#{:error :first} mode) (assoc :autofocus true))))

(defn- remember-me [checked?]
  (c/checkbox-field (cond-> {:id "rememberMe" :name "rememberMe" :label (msg "rememberMe")}
                      checked? (assoc :checked true))))

(defn- sign-in-form []
  [:form {:id "kc-form-login" :class "flex flex-col gap-5" :onsubmit "login.disabled = true; return true;"
          :action "${url.loginAction}" :method "post"}
   (when-ftl credentials-error
             (c/alert {:tone :critical :role "alert"
                       :title (ftl "${kcSanitize(messagesPerField.getFirstError('username','password'))?no_esc}")}
                      (msg "loginErrorHint")))
   (when-ftl "!usernameHidden??" (either-ftl credentials-error (username-field true) (username-field false)))
   (either-ftl credentials-error
               (password-field :error)
               (either-ftl "usernameHidden??" (password-field :first) (password-field :plain)))
   (when-ftl "(realm.rememberMe && !usernameHidden??) || realm.resetPasswordAllowed"
             [:div {:class "flex flex-wrap items-center justify-between gap-x-4 gap-y-2"}
              (when-ftl "realm.rememberMe && !usernameHidden??" (either-ftl "login.rememberMe??" (remember-me true) (remember-me false)))
              (when-ftl "realm.resetPasswordAllowed"
                        [:a {:class "link link-primary text-sm font-medium" :href "${url.loginResetCredentialsUrl}"} (msg "doForgotPassword")])])
   (ftl "<input type=\"hidden\" id=\"id-hidden-input\" name=\"credentialId\" "
        "<#if auth.selectedCredential?has_content>value=\"${auth.selectedCredential}\"</#if>/>")
   (c/button {:type "submit" :size :lg :block? true :id "kc-login" :name "login"} (msg "doLogIn"))])

(defn- registration-or-hint []
  (either-ftl "realm.password && realm.registrationAllowed && !registrationDisabled??"
              [:span (msg "noAccount") " " [:a {:class "link link-primary font-medium" :href "${url.registrationUrl}"} (msg "doRegister")]]
              [:span (msg "noAccountHint")]))

(defn- social-providers []
  (when-ftl "realm.password && social?? && social.providers?has_content"
            [:div {:id "kc-social-providers" :class "mt-6"}
             [:h2 {:class "mb-3 text-sm font-semibold text-muted"} (msg "identity-provider-login-label")]
             [:ul {:class "flex flex-col gap-2"}
              (ftl "<#list social.providers as p>")
              [:li (c/button {:variant :outline :block? true :id "social-${p.alias}" :href "${p.loginUrl}"} (ftl "${p.displayName!}"))]
              (ftl "</#list>")]]))

(defn- login-ftl []
  (page [["displayMessage" "!messagesPerField.existsError('username','password')"]
         ["displayInfo" "realm.password"]]
        [["header" (msg "loginAccountTitle")]
         ["subtitle" (when-ftl "(client.name)?has_content" (msg "loginSubtitle" "client.name"))]
         ["form" (when-ftl "realm.password" (sign-in-form))]
         ["info" (when-ftl "realm.password" (registration-or-hint))]
         ["socialProviders" (social-providers)]]))

(defn- error-ftl []
  (page [["displayMessage" "false"]]
        [["header" (ftl "${kcSanitize(msg(\"errorTitle\"))?no_esc}")]
         ["form" [:div {:id "kc-error-message" :class "flex flex-col gap-5"}
                  (c/alert {:tone :critical :role "alert" :title (ftl "${kcSanitize(message.summary)?no_esc}")})
                  (when-ftl "!skipLink?? && client?? && client.baseUrl?has_content"
                            (c/button {:variant :outline :size :lg :block? true :id "backToApplication" :href "${client.baseUrl}"}
                                      (ftl "${kcSanitize(msg(\"backToApplication\"))?no_esc}")))]]]))

(defn- info-ftl []
  (let [action (fn [href k variant]
                 (c/button {:variant variant :size :lg :block? true :href href} (ftl "${kcSanitize(msg(\"" k "\"))?no_esc}")))]
    (page [["displayMessage" "false"]]
          [["header" (either-ftl "messageHeader??" (ftl "${kcSanitize(msg(\"${messageHeader}\"))?no_esc}") (ftl "${message.summary}"))]
           ;; there is nothing in the card but its title when the message says it all and there is nowhere to go
           ["form" (when-ftl (str "messageHeader?? || requiredActions?? || (!skipLink?? && "
                                  "(pageRedirectUri?has_content || actionUri?has_content || (client.baseUrl)?has_content))")
                             [:div {:id "kc-info-message" :class "flex flex-col gap-5"}
                              (when-ftl "messageHeader?? || requiredActions??"
                                        [:p {:class "text-base"}
                                         (ftl "${message.summary}")
                                         (when-ftl "requiredActions??"
                                                   (ftl "<#list requiredActions>: <b><#items as reqActionItem>"
                                                        "${kcSanitize(msg(\"requiredAction.${reqActionItem}\"))?no_esc}<#sep>, </#items></b></#list>"))])
                              (when-ftl "!skipLink??"
                                        (ftl "<#if pageRedirectUri?has_content>") (action "${pageRedirectUri}" "backToApplication" :primary)
                                        (ftl "<#elseif actionUri?has_content>") (action "${actionUri}" "proceedWithAction" :primary)
                                        (ftl "<#elseif (client.baseUrl)?has_content>") (action "${client.baseUrl}" "backToApplication" :primary)
                                        (ftl "</#if>"))])]])))

