(ns pulse.design.icons
  "Turns the Lucide icons the interface uses into Clojure data (ADR-0026): reads the names in
  `design/icons.edn`, takes each SVG from the lucide-static package and writes
  `libs/ui/src/pulse/ui/icons.cljc`, a map from the name of an icon to the hiccup of its shapes. The text is
  made by `icons-source`, which is pure; only `generate!` reads and writes files."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.string :as str]))

(def names-file "design/icons.edn")
(def package-dir "design/node_modules/lucide-static")
(def output-file "libs/ui/src/pulse/ui/icons.cljc")

(def ^:private shapes #{"path" "circle" "rect" "line" "polyline" "polygon" "ellipse"})

(defn- attributes
  "The attributes of an element as a map from a keyword to a string, in the order they are written."
  [text]
  (into (array-map)
        (map (fn [[_ k v]] [(keyword k) v]))
        (re-seq #"(?<=\s)([A-Za-z][A-Za-z0-9:-]*)=\"([^\"]*)\"" text)))

(defn parse-svg
  "The shapes inside the `<svg>` of the text of a Lucide icon, as hiccup: `[[:path {:d \"...\"}] ...]`.
  Throws an ex-info of type `:pulse.design.icons/unexpected` when the file holds anything else (a group,
  a style, a gradient), because an icon that is not only shapes would not be drawn the same way."
  [svg]
  (let [inside (-> svg
                   (str/replace #"(?s)<!--.*?-->" "")
                   (str/replace #"(?s)^\s*<svg\b[^>]*>" "")
                   (str/replace #"(?s)</svg>\s*$" ""))
        elements (re-seq #"(?s)<([A-Za-z][A-Za-z0-9]*)\b([^>]*?)/>" inside)
        rest-text (str/replace inside #"(?s)<([A-Za-z][A-Za-z0-9]*)\b([^>]*?)/>" "")]
    (when-not (str/blank? rest-text)
      (throw (ex-info "An icon holds more than shapes" {:type ::unexpected :left-over (str/trim rest-text)})))
    (when (empty? elements)
      (throw (ex-info "An icon has no shapes" {:type ::unexpected})))
    (vec (for [[_ tag attrs] elements]
           (do (when-not (contains? shapes tag)
                 (throw (ex-info (str "Not a shape: " tag) {:type ::unexpected :tag tag})))
               [(keyword tag) (attributes attrs)])))))

(defn- shape-source
  "A shape as the text of hiccup, with no commas: `[:circle {:cx \"12\" :cy \"12\" :r \"10\"}]`."
  [[tag attrs]]
  (str "[" tag " {" (str/join " " (map (fn [[k v]] (str k " " (pr-str v))) attrs)) "}]"))

(defn icons-source
  "The text of `icons.cljc` for `icons`, a map from a keyword to the shapes `parse-svg` gives, sorted by name,
  one icon on each line so that a change to one is one line of a diff."
  [icons version]
  (str "(ns pulse.ui.icons\n"
       "  \"GENERATED by `bb design:icons` from the Lucide icons listed in design/icons.edn (lucide-static " version ";\n"
       "  ISC, and MIT for the icons derived from Feather: see NOTICE). Do not edit it. A map from the name of an\n"
       "  icon to the hiccup of its shapes, drawn on a 24 by 24 grid by `pulse.ui.icon`.\")\n"
       "\n"
       "(def icons\n"
       "  {"
       (str/join "\n   " (for [[k shapes] (sort-by (comp name key) icons)]
                           (str k " [" (str/join " " (map shape-source shapes)) "]")))
       "})\n"))

(defn version-of
  "The version in the text of a `package.json`, or nil."
  [text]
  (second (re-find #"\"version\":\s*\"([^\"]+)\"" text)))

(defn- package-version []
  (version-of (slurp (io/file package-dir "package.json") :encoding "UTF-8")))

(defn generate!
  "Writes `libs/ui/src/pulse/ui/icons.cljc` for the icons in `design/icons.edn`."
  []
  (let [wanted (edn/read-string (slurp names-file :encoding "UTF-8"))
        _ (when-not (and (vector? wanted) (every? keyword? wanted) (= (count wanted) (count (set wanted))))
            (throw (ex-info (str names-file " must be a vector of icon names with no repeats") {:type ::invalid-list})))
        icons (into {}
                    (for [k wanted
                          :let [file (io/file package-dir "icons" (str (name k) ".svg"))]]
                      (do (when-not (.exists file)
                            (throw (ex-info (str "No such icon in lucide-static: " (name k)) {:type ::unknown-icon :icon k})))
                          [k (parse-svg (slurp file :encoding "UTF-8"))])))]
    (spit output-file (icons-source icons (package-version)) :encoding "UTF-8")
    (println "Wrote" (count icons) "icons to" output-file)))
